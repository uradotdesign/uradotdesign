export function extractClasses(value, sink = new Set()) {
  if (Array.isArray(value)) value.forEach((v) => extractClasses(v, sink));
  else if (value && typeof value === "object")
    Object.values(value).forEach((v) => extractClasses(v, sink));
  else if (typeof value === "string") {
    for (const match of value.matchAll(
      /\bclass\s*=\s*(?:"([^"]*)"|'([^']*)')/gi
    )) {
      for (const token of (match[1] ?? match[2]).split(/\s+/)) {
        if (
          token.length <= 160 &&
          /^[A-Za-z0-9_:/.,%#[\]()!+\\-]+$/.test(token)
        )
          sink.add(token);
      }
    }
  }
  return sink;
}
export function classManifest(classes) {
  const sorted = [...classes].sort();
  return (
    "<!-- AUTO-GENERATED by scripts/scan-cms-tailwind.mjs. Public CSS classes only. -->\n" +
    sorted.map((token) => `<div class="${token}"></div>`).join("\n") +
    "\n"
  );
}
