import { copyFile, readFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { createHash } from "node:crypto";
const target = new URL(
  "../src/styles/cms-classes.generated.html",
  import.meta.url
);
const source = process.env.CMS_CLASSES_INPUT || "/run/secrets/cms-classes";
if (existsSync(source)) {
  const manifest = await readFile(source, "utf8");
  const expected = process.env.CMS_CLASSES_SHA256;
  if (
    expected &&
    expected !== "committed" &&
    createHash("sha256").update(manifest).digest("hex") !== expected
  )
    throw new Error(
      "CMS class manifest changed after the build was prepared. Rescan and retry."
    );
  if (
    !manifest.startsWith(
      "<!-- AUTO-GENERATED by scripts/scan-cms-tailwind.mjs."
    )
  )
    throw new Error("Invalid CMS class manifest.");
  await copyFile(source, target);
  console.log("Building with the freshly scanned CMS class manifest.");
} else {
  if (process.env.REQUIRE_CMS_CLASSES === "true")
    throw new Error(
      "Production requires a fresh CMS scan. Run scripts/prepare-cms-css.sh first."
    );
  await readFile(target, "utf8");
  console.log(
    "Building with the committed CMS class baseline (offline/CI mode)."
  );
}
